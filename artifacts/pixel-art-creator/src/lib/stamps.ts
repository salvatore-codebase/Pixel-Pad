import type { StampShape } from './types';

function makeStamp(id: string, name: string, icon: string, w: number, h: number, pixels: Array<[number, number, string]>): StampShape {
  return {
    id,
    name,
    icon,
    width: w,
    height: h,
    pixels: pixels.map(([x, y, color]) => ({ x, y, color })),
  };
}

function rect(x1: number, y1: number, x2: number, y2: number, color: string): Array<[number, number, string]> {
  const result: Array<[number, number, string]> = [];
  for (let y = y1; y <= y2; y++) {
    for (let x = x1; x <= x2; x++) {
      result.push([x, y, color]);
    }
  }
  return result;
}

